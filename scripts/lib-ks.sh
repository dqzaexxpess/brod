# Помощник для окон проверок: снять правила киллсвитча (таблица inet brod_ks). Подключать после `cd` в корень репозитория: . scripts/lib-ks.sh
# Сначала командой самого демона (у него есть cap_net_admin), запасной путь — sudo без запроса пароля (если он уже в кэше).
# Вызывается при любом выходе из окна и в сторожевых таймерах: жёстко убитый демон правила не снимает (так и задумано), а окно
# проверки не должно оставлять сеть заблокированной.
ks_release() {
  ./bin/brodd --release-killswitch >/dev/null 2>&1 || sudo -n nft delete table inet brod_ks >/dev/null 2>&1 || true
}
