/// Рисуются ли флаги-эмодзи. Везде да: на Windows системный шрифт (Segoe UI Emoji) их не знает, но в приложение вшит набор флагов
/// (NotoFlags, см. ThemeData.fontFamilyFallback). Если где-то флаги не рисуются, достаточно вернуть false — вместо них пойдёт код страны.
/// В тестах подменяется.
bool? flagEmojiOverride;

bool get flagEmojiSupported => flagEmojiOverride ?? true;

/// Флаг-эмодзи по ISO-коду страны («DE» → 🇩🇪); где флаги не рисуются — сам код («DE»).
String flagOf(String code) {
  if (code.length != 2 || code == 'XX' || code == 'T1') return '🌐';
  final a = code.toUpperCase().codeUnits;
  if (a.any((c) => c < 65 || c > 90)) return '🌐';
  if (!flagEmojiSupported) return String.fromCharCodes(a);
  return String.fromCharCodes(a.map((c) => 0x1F1E6 + c - 65));
}

