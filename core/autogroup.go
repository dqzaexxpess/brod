package core

import "time"

// Авто-группа (M3c, v1) — заготовка. Ручной режим остаётся единственным (P1: узел не меняется без пользователя); авто-группа —
// отдельная сущность, которую пользователь включает явно, и только она вправе менять свой узел сама.
//
// Контракт будущей реализации (чтобы её можно было вставить, не трогая остальное ядро):
//   - Пул: только узлы, прошедшие L2 (и google-api, если нужно) в ТЕКУЩЕЙ сети (netKey), без security=none/insecure по политике P6.
//   - Гистерезис против «флаппинга»: смена только если текущий узел деградировал (HealthFails подряд) ИЛИ кандидат лучше на
//     MinImprovement и текущий выбран не раньше MinHold; не чаще одной смены за Cooldown.
//   - Каждая смена — событие switch с инициатором "auto-group" и запись выбора; активный узел ручного режима группа не трогает.
//   - Переключение через Core.connectLocked (тот же путь, что и у пользователя) — вместе с interrupt_existing и gc.
type AutoPolicy struct {
	MinImprovement float64       // во сколько раз кандидат должен быть лучше (по задержке), чтобы сменить здоровый узел
	MinHold        time.Duration // сколько узел держится после выбора
	Cooldown       time.Duration // минимальный интервал между сменами
}

// SetAutoGroup — настройка включения авто-группы.
const SetAutoGroup = "auto.enabled"

// AutoGroupEnabled: авто-группа не реализована, всегда false.
func (c *Core) AutoGroupEnabled() bool { return false }
